#!/usr/bin/env python3
"""Builds content.js from the readable files in src/.

    python3 build.py

src/style.css  - the look of the overlay
src/body.html  - the overlay's markup
src/NN-*.js    - the overlay's code, joined in numeric order
"""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
read = lambda p: open(os.path.join(HERE, p), encoding="utf-8").read()

css = read("src/style.css")
html = read("src/body.html")
parts = sorted(glob.glob(os.path.join(HERE, "src", "[0-9][0-9]-*.js")))
app = "\n".join(open(p, encoding="utf-8").read().rstrip("\n") for p in parts)

TEMPLATE = r'''/* WebTroller (c) 2026 Vertzz - developed by Vertzz - https://t.me/vertzz_official
   Generated by build.py from the files in src/. Edit those, then run: python3 build.py */
(()=>{
if(window.__WT)return;window.__WT=1;
const CSS=@@CSS@@;
const HTML=@@HTML@@;
chrome.storage.local.get(["wt","emu3"],r=>start(r.wt||r.emu3||null));
function start(saved){
const host=document.createElement("div");host.id="webtroller-host";
host.style.cssText="all:initial;position:fixed;inset:0;z-index:2147483647;pointer-events:none";
const root=host.attachShadow({mode:"open"});
root.innerHTML="<style>"+CSS+'</style><div id="shell" data-mode="play" data-grid="1">'+HTML+"</div>";
document.documentElement.appendChild(host);
@@APP@@
}
})();
'''
out = TEMPLATE.replace("@@CSS@@", json.dumps(css)).replace("@@HTML@@", json.dumps(html)).replace("@@APP@@", app)
open(os.path.join(HERE, "content.js"), "w", encoding="utf-8").write(out)
print("built content.js:", len(out), "bytes from", len(parts), "script files")
